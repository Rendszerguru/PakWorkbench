	public interface ICustomIcon : IDisposable
	{
		int BaseAdvanceWidth { get; }
		Color? TextColor { get; }
		void UpdateDpi(float dpiScale);
		void Draw(Graphics g, float iconX, float iconY, Color bgColor);
	}

	public abstract class BaseCustomIcon(Color iconColor) : ICustomIcon
	{
		protected readonly SolidBrush _brush = new(iconColor);
		protected abstract RectangleF[] IconRects { get; }

		public int BaseAdvanceWidth => 18;
		public abstract Color? TextColor { get; }

		public void UpdateDpi(float dpiScale) { }

		public void Draw(Graphics g, float iconX, float iconY, Color bgColor)
		{
			var m = g.Transform;
			g.TranslateTransform(iconX, iconY);

			float scale = 16f / 256f;
			g.ScaleTransform(scale, scale);

			g.PixelOffsetMode = PixelOffsetMode.Half;
			g.SmoothingMode = SmoothingMode.None;

			g.FillRectangles(_brush, IconRects);

			g.Transform = m;
			g.PixelOffsetMode = PixelOffsetMode.Default;
		}

		public void Dispose()
		{
			_brush?.Dispose();
			GC.SuppressFinalize(this);
		}
	}

